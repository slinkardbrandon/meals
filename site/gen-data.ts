import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { loadDinners, repoRoot } from '../src/dinners'
import type { SiteData } from './app/types'
import { buildSiteData } from './data'

export const loadSiteData = async (): Promise<SiteData> => {
  const paths = await Array.fromAsync(new Bun.Glob('plans/**/W*.md').scan({ cwd: repoRoot }))
  const planFiles = await Promise.all(paths.sort().map(p => readFile(join(repoRoot, p), 'utf8')))
  return buildSiteData({ dinners: await loadDinners(), planFiles })
}

export const DATA_PATH = join(repoRoot, 'site/app/data.gen.ts')

/** Writes `site/app/data.gen.ts` for the app bundle and `tsc`. */
export const writeSiteData = async () => {
  const data = await loadSiteData()
  const source = [
    '// Generated by site/gen-data.ts. Do not edit.',
    "import type { SiteData } from './types'",
    '',
    `export default ${JSON.stringify(data, null, 2)} satisfies SiteData`,
    '',
  ].join('\n')
  await writeFile(DATA_PATH, source)
}

if (import.meta.main) await writeSiteData()
